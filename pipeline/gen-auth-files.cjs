#!/usr/bin/env node
/**
 * gen-auth-files.cjs — Emit bin/auth-files.sh from bin/silly-auth.js.
 *
 * bin/silly-auth.js is the canonical manifest of auth filenames
 * (codex-auth.json, codex-oauth.json, claude-oauth.json) + the macOS
 * keychain path for Node launchers + adapters. Bash launchers need the
 * same constants. This generator makes silly-auth.js the sole source of
 * truth; the bash shim is a derived artifact, checked into the repo and
 * asserted byte-equal by tests/gen-auth-files.test.cjs.
 *
 * Run: `node pipeline/gen-auth-files.cjs`          — writes bin/auth-files.sh.
 *      `node pipeline/gen-auth-files.cjs --check`  — readonly: exit 0 if the
 *        committed shim matches canonical, exit 1 with drift hint otherwise.
 *        Useful as a CI / pre-commit step without running the full test suite.
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const AUTH_JS = path.join(ROOT, 'bin', 'silly-auth.js');
const OUT_SH = path.join(ROOT, 'bin', 'auth-files.sh');

function extractArray(src, key) {
  const m = src.match(new RegExp(`${key}:\\s*\\[([^\\]]*)\\]`));
  if (!m) throw new Error(`AUTH_FILES.${key} not found in silly-auth.js`);
  return Array.from(m[1].matchAll(/['"]([^'"]+)['"]/g)).map(x => x[1]);
}

function extractKeychainRel(src) {
  const m = src.match(/CLAUDE_MACOS_KEYCHAIN\s*=\s*path\.join\(os\.homedir\(\)\s*,([^)]+)\)/);
  if (!m) throw new Error('CLAUDE_MACOS_KEYCHAIN definition not found in silly-auth.js');
  const parts = Array.from(m[1].matchAll(/'([^']+)'/g)).map(x => x[1]);
  return parts.join('/');
}

function render(codex, claude, keychainRel) {
  if (codex.length !== 2) {
    throw new Error(`expected 2 codex auth files, got ${codex.length}: ${JSON.stringify(codex)}`);
  }
  if (claude.length !== 1) {
    throw new Error(`expected 1 claude auth file, got ${claude.length}: ${JSON.stringify(claude)}`);
  }
  const authName = codex.find(n => /-auth\.json$/.test(n));
  const oauthName = codex.find(n => /-oauth\.json$/.test(n));
  if (!authName || !oauthName) {
    throw new Error(`expected one *-auth.json and one *-oauth.json codex file, got ${JSON.stringify(codex)}`);
  }
  return `# auth-files.sh — generated by pipeline/gen-auth-files.cjs, DO NOT EDIT BY HAND.
# Canonical source: bin/silly-auth.js (AUTH_FILES + CLAUDE_MACOS_KEYCHAIN).
# Regenerate: node pipeline/gen-auth-files.cjs
# Idempotency asserted by tests/gen-auth-files.test.cjs.

CODEX_AUTH="${authName}"
CODEX_OAUTH="${oauthName}"
CLAUDE_OAUTH="${claude[0]}"
CLAUDE_CRED="$HOME/${keychainRel}"
`;
}

function generate() {
  const src = fs.readFileSync(AUTH_JS, 'utf8');
  const codex = extractArray(src, 'codex');
  const claude = extractArray(src, 'claude');
  const keychainRel = extractKeychainRel(src);
  return render(codex, claude, keychainRel);
}

function firstDiffSummary(expected, actual) {
  const le = expected.split('\n');
  const la = actual.split('\n');
  const n = Math.min(le.length, la.length);
  for (let i = 0; i < n; i++) {
    if (le[i] !== la[i]) {
      return `line ${i + 1}:\n  expected: ${JSON.stringify(le[i])}\n  actual:   ${JSON.stringify(la[i])}`;
    }
  }
  if (le.length !== la.length) {
    return `line count: expected ${le.length}, actual ${la.length}`;
  }
  return '(content matches but bytes differ — check trailing newline)';
}

function runCheck() {
  const expected = generate();
  const rel = path.relative(ROOT, OUT_SH);
  if (!fs.existsSync(OUT_SH)) {
    console.error(`[gen-auth-files --check] FAIL: ${rel} is missing.`);
    console.error('  Fix: node pipeline/gen-auth-files.cjs');
    process.exit(1);
  }
  const committed = fs.readFileSync(OUT_SH, 'utf8');
  if (committed === expected) {
    console.log(`[gen-auth-files --check] OK: ${rel} matches canonical source.`);
    return;
  }
  console.error(`[gen-auth-files --check] FAIL: ${rel} is out of sync with bin/silly-auth.js.`);
  console.error(`  First divergence — ${firstDiffSummary(expected, committed)}`);
  console.error('  Fix: node pipeline/gen-auth-files.cjs');
  process.exit(1);
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const unknown = args.filter(a => a !== '--check');
  if (unknown.length) {
    console.error(`[gen-auth-files] unknown argument(s): ${unknown.join(' ')}`);
    console.error('  usage: node pipeline/gen-auth-files.cjs [--check]');
    process.exit(2);
  }
  try {
    if (args.includes('--check')) {
      runCheck();
    } else {
      const content = generate();
      fs.writeFileSync(OUT_SH, content);
      console.log(`[gen-auth-files] wrote ${path.relative(ROOT, OUT_SH)} (${content.length} bytes)`);
    }
  } catch (e) {
    console.error('[gen-auth-files] ERROR:', e.message);
    process.exit(1);
  }
}

module.exports = { extractArray, extractKeychainRel, render, generate, runCheck };
